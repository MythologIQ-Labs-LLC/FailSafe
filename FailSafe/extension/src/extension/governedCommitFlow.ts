/**
 * governedCommitFlow — the operator-confirmed orchestration around `commitPushOpenPr`,
 * shared by the Organize and Initialize commands. After a command applies workspace
 * edits, this asks once whether to commit+push+PR them; on "No" it records what was
 * done (and when) to the audit ledger so the changes are identified, not anonymous drift.
 *
 * The changed-path set is computed by the CALLER as a before/after `git status` diff
 * (proposal-agnostic, precise — never sweeps unrelated dirty files into the commit).
 *
 * PURE wiring over injected deps (confirm / git / ledger / clock) — testable, no vscode.
 */

import { commitPushOpenPr, type GitRunner, type GovernedCommitResult } from './governedCommit';
import type { GitHubPostFn } from '../integrations/github-checks/github-checks-client';
import type { Connection } from '../integrations/credentials/credentialGates';
import { bindGitRemote } from '../integrations/github-checks/github-checks-map';
import { apiBaseFor } from '../integrations/github-checks/github-host-affinity';

export interface GovernedFlowDeps {
  workspaceRoot: string;
  git: GitRunner;
  /** Operator confirmation (vscode.window.showInformationMessage in production). */
  confirm: (message: string) => Promise<boolean>;
  /** Record a declined commit to the audit ledger (LedgerManager.appendEntry in production). */
  recordDeclined: (info: { action: string; changes: string[]; at: string }) => Promise<void>;
  now: () => string;     // ISO timestamp (injected for tests)
  post?: GitHubPostFn;
  token?: string;
  apiBaseUrl?: string;
  branchPrefix?: string; // default "fix"
  /** #532 (plan-532c LD7): offered the bound commit after committed / pushed / pr; never changes the result. */
  linkCommit?: GovernedCommitLinkFn;
  base?: string;         // default "main"
  describeArchitecture?: (paths: string[]) => Promise<string[]>; // B311: warn-only affected-architecture lines (see architectureNote)
}

/** #532 (plan-532c LD7): what the link offer is given: the bound commit and the run that made it. */
export type GovernedCommitLinkFn = (
  result: GovernedCommitResult & { commitSha: string },
  run: { action: string; paths: string[] },
) => Promise<void>;

export type GovernedFlowResult = GovernedCommitResult | { step: 'noop' } | { step: 'declined' };

const slugStamp = (iso: string): string => iso.replace(/[^0-9]/g, '').slice(0, 14);

export async function runGovernedCommitFlow(
  action: string,                 // "organize" | "initialize"
  changedPaths: string[],
  executedLabels: string[],
  deps: GovernedFlowDeps,
): Promise<GovernedFlowResult> {
  if (changedPaths.length === 0) return { step: 'noop' };

  const architecture = await architectureNote(deps, changedPaths);
  const destination = await githubDestinationNote(deps);
  const approved = await deps.confirm(
    `FailSafe ${action} applied ${changedPaths.length} change(s). Commit, push & open a PR for them?${architecture}${destination}`,
  );
  if (!approved) {
    await deps.recordDeclined({ action, changes: executedLabels, at: deps.now() });
    return { step: 'declined' };
  }

  const branch = `${deps.branchPrefix || 'fix'}/${action}-${slugStamp(deps.now())}`;
  const bullets = executedLabels.map((l) => `- ${l}`).join('\n');
  const message = `chore(${action}): apply ${changedPaths.length} workspace change(s)\n\n${bullets}`;
  const prBody = `Automated by FailSafe **${action}** (operator-confirmed).\n\n### Changes\n${bullets}\n\n🤖 Generated by the FailSafe extension.`;

  const result = await commitPushOpenPr(
    { workspaceRoot: deps.workspaceRoot, paths: changedPaths, branch, message, base: deps.base || 'main', prTitle: `chore(${action}): workspace cleanup`, prBody },
    { git: deps.git, post: deps.post, token: deps.token, apiBaseUrl: deps.apiBaseUrl },
  );
  // #532 (plan-532c LD7b): offer the bound commit for linking; the offer never changes the result.
  if (deps.linkCommit && result.commitSha && (result.step === 'committed' || result.step === 'pushed' || result.step === 'pr')) {
    try {
      await deps.linkCommit({ ...result, commitSha: result.commitSha }, { action, paths: changedPaths });
    } catch { /* the link offer is best-effort; the commit stands */ }
  }
  return result;
}

/**
 * #538 (B265): the PR step's options from the credential gate's connection, so the
 * token is sent only to the endpoint it was paired with (the GitHub default when none).
 */
export function governedCommitPrStep(
  connection: Connection | undefined, post: GitHubPostFn,
): Pick<GovernedFlowDeps, 'post' | 'token' | 'apiBaseUrl'> {
  return { post, token: connection?.credential, apiBaseUrl: connection?.endpoint };
}

/** Display any custom GitHub destination before consenting to commit, push and PR. */
async function githubDestinationNote(deps: GovernedFlowDeps): Promise<string> {
  if (!deps.post || !deps.token || !deps.apiBaseUrl?.trim()) return '';
  const api = apiBaseFor(deps.apiBaseUrl);
  if (!api.ok) return ' GitHub PR API destination is invalid; authenticated PR publishing will be refused.';
  try {
    const remote = await deps.git(['remote', 'get-url', 'origin'], deps.workspaceRoot);
    const id = remote.code === 0
      ? bindGitRemote(remote.stdout.trim(), api.base.apiHost, true) : null;
    if (!id) return ' GitHub PR remote/API identity cannot be confirmed; authenticated PR publishing will be refused.';
    return ` GitHub PR destination: ${api.base.baseUrl}/repos/${id.owner}/${id.repo} (remote ${id.host}). The Workspace GitHub token would be sent to ${api.base.origin}.`;
  } catch {
    return ' GitHub PR destination cannot be read; authenticated PR publishing will be refused.';
  }
}

/**
 * B311 (plan-b311-b312 LD8): the prompt's warn-only affected-architecture sentence, from lines the
 * caller has already capped; '' when there are none or describe throws, so the prompt is unchanged.
 */
async function architectureNote(deps: GovernedFlowDeps, paths: string[]): Promise<string> {
  if (!deps.describeArchitecture) return '';
  try {
    const lines = await deps.describeArchitecture(paths);
    return Array.isArray(lines) && lines.length ? ` Architecture decisions these files touch (warn-only): ${lines.join('; ')}.` : '';
  } catch {
    return '';
  }
}
