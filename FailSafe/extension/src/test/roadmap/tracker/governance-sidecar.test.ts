// Functional tests for the governance tracker sidecar emitter (GH #194; A.2).
// Pure over injected SidecarDeps → deterministic. Backend logic (no visual surface):
// the emitter materializes the FX862 projection to a GENERATED sidecar and must NEVER
// touch the operator's hand-curated docs/roadmap/programs.yaml (FX859). Render is
// unchanged (no Playwright gate); consumption of the sidecar is a follow-up (A.2b).

